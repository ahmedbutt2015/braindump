-- ── AI action audit log ───────────────────────────────────────────────────────
-- DRAFT — needs human review before it is run in the Supabase SQL Editor.
-- Run after 000, 001, 002 and 003.
--
-- One row per model-proposed mutation to an EXISTING task (an enrichment or a
-- subtask addition), whatever lib/ai-guard.ts decided:
--   applied  — written to the task; before_value/after_value make it revertable
--   proposed — failed a trust check; stored for a human, task untouched
--   rejected — structurally invalid; kept only as an audit record
--   reverted — was applied, then undone (reverted_at is set)

CREATE TABLE IF NOT EXISTS ai_actions (
  id             UUID         DEFAULT gen_random_uuid() PRIMARY KEY,
  user_id        UUID         NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  -- Groups every action produced by one extract-tasks call. Generated by the route.
  request_id     UUID         NOT NULL,
  brain_dump_id  UUID         REFERENCES brain_dumps(id) ON DELETE SET NULL,
  task_id        UUID         REFERENCES tasks(id) ON DELETE SET NULL,
  kind           TEXT         NOT NULL
    CONSTRAINT ai_actions_kind_check CHECK (kind IN ('enrichment', 'subtask_addition')),
  status         TEXT         NOT NULL
    CONSTRAINT ai_actions_status_check CHECK (status IN ('applied', 'proposed', 'reverted', 'rejected')),
  field          TEXT         NOT NULL
    CONSTRAINT ai_actions_field_check CHECK (field IN ('description', 'subtasks')),
  -- Value of tasks.<field> before / after the change, as jsonb (description is a
  -- JSON string or SQL NULL, subtasks is a JSON array). SQL NULL means "no value".
  before_value   JSONB,
  after_value    JSONB,
  -- GuardDecision.payload: { taskId, text, evidence }
  payload        JSONB        NOT NULL DEFAULT '{}',
  evidence       TEXT,
  -- GuardReason codes (lib/ai-guard.ts); empty for a clean apply.
  reasons        TEXT[]       NOT NULL DEFAULT '{}',
  created_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
  reverted_at    TIMESTAMPTZ,

  CONSTRAINT ai_actions_kind_field_check CHECK (
    (kind = 'enrichment' AND field = 'description')
    OR (kind = 'subtask_addition' AND field = 'subtasks')
  ),
  CONSTRAINT ai_actions_reverted_at_check CHECK ((status = 'reverted') = (reverted_at IS NOT NULL))
);

-- ── RLS ───────────────────────────────────────────────────────────────────────
-- Split per command instead of FOR ALL (as 001/002 do) so there is deliberately
-- no DELETE policy: with RLS on and no policy, DELETE is denied. The audit log
-- cannot be erased through the API; rows leave only via the auth.users cascade.
ALTER TABLE ai_actions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "ai_actions_select_own" ON ai_actions;
CREATE POLICY "ai_actions_select_own"
  ON ai_actions FOR SELECT
  TO authenticated
  USING ((SELECT auth.uid()) = user_id);

-- A row may only point at a task / dump the same user owns. The FKs alone only
-- prove the id exists, not whose it is. The subqueries run under the caller's
-- own RLS, so another user's rows are invisible to them.
DROP POLICY IF EXISTS "ai_actions_insert_own" ON ai_actions;
CREATE POLICY "ai_actions_insert_own"
  ON ai_actions FOR INSERT
  TO authenticated
  WITH CHECK (
    (SELECT auth.uid()) = user_id
    AND (task_id IS NULL
         OR EXISTS (SELECT 1 FROM tasks t WHERE t.id = task_id AND t.user_id = (SELECT auth.uid())))
    AND (brain_dump_id IS NULL
         OR EXISTS (SELECT 1 FROM brain_dumps d WHERE d.id = brain_dump_id AND d.user_id = (SELECT auth.uid())))
  );

DROP POLICY IF EXISTS "ai_actions_update_own" ON ai_actions;
CREATE POLICY "ai_actions_update_own"
  ON ai_actions FOR UPDATE
  TO authenticated
  USING ((SELECT auth.uid()) = user_id)
  WITH CHECK ((SELECT auth.uid()) = user_id);

-- The UPDATE policy only exists so a row can be marked reverted. Narrow the
-- column privilege so before_value / after_value / payload are write-once.
REVOKE UPDATE ON ai_actions FROM authenticated;
GRANT UPDATE (status, reverted_at) ON ai_actions TO authenticated;

-- ── Indexes ───────────────────────────────────────────────────────────────────
CREATE INDEX IF NOT EXISTS ai_actions_user_created_idx
  ON ai_actions (user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS ai_actions_task_created_idx
  ON ai_actions (task_id, created_at DESC);

-- Review inbox: only the proposals still waiting on a human.
CREATE INDEX IF NOT EXISTS ai_actions_proposed_idx
  ON ai_actions (user_id, created_at DESC)
  WHERE status = 'proposed';

-- ── apply_ai_action ───────────────────────────────────────────────────────────
-- Compare-and-swap on one field of one task, plus its audit row, in a single
-- transaction (a plpgsql function body is one statement to the caller, so any
-- RAISE rolls back the task update too).
--
--   apply : p_revert_of is NULL. Needs p_task_id, p_field, p_kind, p_request_id.
--           Sets tasks.<p_field> = p_new only if it currently equals p_expected,
--           then inserts an 'applied' ai_actions row.
--   revert: p_revert_of = an 'applied' ai_actions.id. Task, field, expected and
--           new value are taken from that row (expected = its after_value,
--           new = its before_value); every other argument is ignored. The row
--           is flipped to 'reverted' instead of a second row being inserted.
--
-- Outcomes (expected races, returned): applied | reverted | conflict |
-- task_not_found | not_revertable. Caller bugs (bad field, wrong value type,
-- no session) RAISE instead.
--
-- SECURITY INVOKER: runs as the caller, so RLS on tasks and ai_actions applies.
-- The user_id filters below are belt-and-braces (CLAUDE.md convention).
CREATE OR REPLACE FUNCTION apply_ai_action(
  p_task_id        UUID    DEFAULT NULL,
  p_field          TEXT    DEFAULT NULL,
  p_expected       JSONB   DEFAULT NULL,
  p_new            JSONB   DEFAULT NULL,
  p_kind           TEXT    DEFAULT NULL,
  p_request_id     UUID    DEFAULT NULL,
  p_brain_dump_id  UUID    DEFAULT NULL,
  p_payload        JSONB   DEFAULT '{}',
  p_evidence       TEXT    DEFAULT NULL,
  p_reasons        TEXT[]  DEFAULT '{}',
  p_revert_of      UUID    DEFAULT NULL
)
RETURNS TABLE (outcome TEXT, action_id UUID)
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_uid      UUID  := auth.uid();
  v_orig     ai_actions%ROWTYPE;
  v_task_id  UUID  := p_task_id;
  v_field    TEXT  := p_field;
  v_kind     TEXT  := p_kind;
  -- JSON null and SQL NULL both mean "no value"; fold them together so a client
  -- sending {"p_expected": null} compares equal to an empty description.
  v_expected JSONB := NULLIF(p_expected, 'null'::JSONB);
  v_new      JSONB := NULLIF(p_new, 'null'::JSONB);
  v_current  JSONB;
  v_id       UUID;
BEGIN
  IF v_uid IS NULL THEN
    RAISE EXCEPTION 'apply_ai_action: no authenticated user' USING ERRCODE = '28000';
  END IF;

  IF p_revert_of IS NOT NULL THEN
    -- Row lock serialises two concurrent reverts of the same action.
    SELECT * INTO v_orig
      FROM ai_actions a
     WHERE a.id = p_revert_of AND a.user_id = v_uid AND a.status = 'applied'
       FOR UPDATE;
    -- task_id is NULL if the task was deleted since; there is nothing to restore.
    IF NOT FOUND OR v_orig.task_id IS NULL THEN
      RETURN QUERY SELECT 'not_revertable'::TEXT, NULL::UUID;
      RETURN;
    END IF;
    v_task_id  := v_orig.task_id;
    v_field    := v_orig.field;
    v_kind     := v_orig.kind;
    v_expected := v_orig.after_value;
    v_new      := v_orig.before_value;
  ELSIF v_task_id IS NULL OR v_kind IS NULL OR p_request_id IS NULL THEN
    RAISE EXCEPTION 'apply_ai_action: p_task_id, p_kind and p_request_id are required'
      USING ERRCODE = '22023';
  END IF;

  -- Allowlist. Anything else is a caller bug; the field name never reaches SQL text.
  IF v_field IS NULL OR v_field NOT IN ('description', 'subtasks') THEN
    RAISE EXCEPTION 'apply_ai_action: field % is not allowed', v_field USING ERRCODE = '22023';
  END IF;

  -- Value shape per field: description is a JSON string (or NULL), subtasks an array.
  IF v_field = 'description' AND v_new IS NOT NULL AND jsonb_typeof(v_new) <> 'string' THEN
    RAISE EXCEPTION 'apply_ai_action: description must be a JSON string or null' USING ERRCODE = '22023';
  END IF;
  IF v_field = 'subtasks' AND (v_new IS NULL OR jsonb_typeof(v_new) <> 'array') THEN
    RAISE EXCEPTION 'apply_ai_action: subtasks must be a JSON array' USING ERRCODE = '22023';
  END IF;

  -- Lock the task row and read the current value of the chosen field.
  SELECT CASE v_field
           WHEN 'description' THEN to_jsonb(t.description)
           WHEN 'subtasks'    THEN t.subtasks
         END
    INTO v_current
    FROM tasks t
   WHERE t.id = v_task_id AND t.user_id = v_uid
     FOR UPDATE;

  IF NOT FOUND THEN
    RETURN QUERY SELECT 'task_not_found'::TEXT, NULL::UUID;
    RETURN;
  END IF;

  -- Someone (user edit, another dump, an earlier apply) changed it since the
  -- caller read it. Write nothing; the caller decides what to do with the action.
  IF v_current IS DISTINCT FROM v_expected THEN
    RETURN QUERY SELECT 'conflict'::TEXT, NULL::UUID;
    RETURN;
  END IF;

  -- updated_at is maintained by the tasks_set_updated_at trigger (migration 002).
  UPDATE tasks t
     SET description = CASE v_field WHEN 'description' THEN v_new #>> '{}' ELSE t.description END,
         subtasks    = CASE v_field WHEN 'subtasks'    THEN v_new          ELSE t.subtasks    END
   WHERE t.id = v_task_id AND t.user_id = v_uid;

  IF p_revert_of IS NULL THEN
    INSERT INTO ai_actions (
      user_id, request_id, brain_dump_id, task_id, kind, status, field,
      before_value, after_value, payload, evidence, reasons
    ) VALUES (
      v_uid, p_request_id, p_brain_dump_id, v_task_id, v_kind, 'applied', v_field,
      v_current, v_new, COALESCE(p_payload, '{}'), p_evidence, COALESCE(p_reasons, '{}')
    )
    RETURNING id INTO v_id;
    RETURN QUERY SELECT 'applied'::TEXT, v_id;
  ELSE
    UPDATE ai_actions a
       SET status = 'reverted', reverted_at = NOW()
     WHERE a.id = v_orig.id;
    RETURN QUERY SELECT 'reverted'::TEXT, v_orig.id;
  END IF;
END;
$$;

-- Default PUBLIC execute (and Supabase's explicit anon grant) is not wanted;
-- the function is useless without a session anyway, so this is just tidiness.
REVOKE EXECUTE ON FUNCTION apply_ai_action(UUID, TEXT, JSONB, JSONB, TEXT, UUID, UUID, JSONB, TEXT, TEXT[], UUID)
  FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION apply_ai_action(UUID, TEXT, JSONB, JSONB, TEXT, UUID, UUID, JSONB, TEXT, TEXT[], UUID)
  TO authenticated;
